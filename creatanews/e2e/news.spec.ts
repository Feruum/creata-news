import { expect,test } from '@playwright/test'
test('published stories render server-side with real links and accessible menu',async({page,request})=>{
  const response=await request.get('/api/creata/v1/public/articles?locale=ru');expect(response.ok()).toBeTruthy()
  const{items}=await response.json();test.skip(!items.length,'Run explicit development seed to exercise published stories')
  const html=await request.get('/ru');await expect(html).toBeOK()
  const serverHeadline=await page.evaluate(source=>new DOMParser().parseFromString(source,'text/html').querySelector('#home-spotlight-title')?.textContent,await html.text())
  expect(serverHeadline).toBe(items[0].title.ru)
  const hydrated=page.waitForResponse(response=>response.url().endsWith('/auth/me'))
  await page.goto('/ru');await hydrated;await expect(page.locator('#home-spotlight-title')).toHaveText(items[0].title.ru)
  const header=page.getByRole('banner')
  const quickLinks=header.getByRole('navigation',{name:'Быстрые ссылки'})
  await expect(quickLinks).toBeVisible()
  await expect(quickLinks.getByRole('link')).toHaveText(['О Creata','Последние новости','Утро Creata','Главная V2'])
  await expect(page.locator('.bottom-nav')).not.toBeVisible()
  await expect(page.locator('.masthead,.primary-nav,.topline')).toHaveCount(0)
  await page.getByRole('button',{name:'Открыть меню'}).click();await expect(page.locator('dialog')).toBeVisible()
  await expect(page.locator('dialog').getByRole('heading',{name:'Темы',exact:true})).toBeVisible()
  await page.keyboard.press('Escape');await expect(page.locator('dialog')).not.toBeVisible()
  const leadLink=page.getByRole('heading',{level:1}).getByRole('link',{name:items[0].title.ru,exact:true})
  await expect(leadLink).toHaveAttribute('href',`/ru/articles/${items[0].slug}`)
  await leadLink.click();await expect(page).toHaveURL(`/ru/articles/${items[0].slug}`)
  await expect(page.getByRole('heading',{level:1})).toHaveText(items[0].title.ru)
  await expect(page.locator('meta[property="og:title"]')).toHaveAttribute('content',items[0].title.ru)
  await expect(page.locator('link[rel="canonical"]')).toHaveAttribute('href',new RegExp(`/ru/articles/${items[0].slug}$`))
})
