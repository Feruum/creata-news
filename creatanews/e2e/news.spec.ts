test('prototype opportunities retain images, audience, countdown, responsive grid and current theme',async({page,request})=>{
  const {items}=await(await request.get('/api/creata/v1/public/opportunities?locale=ru')).json()
  test.skip(!items.some((item:any)=>item.photo&&item.forWhom?.ru),'Run explicit prototype opportunity seed')
  const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message))
  for(const theme of ['light','dark']){
    await page.addInitScript(value=>localStorage.setItem('creata:theme',value),theme)
    await page.goto('/ru');await page.locator('[aria-controls="creata-menu"]').click();await page.keyboard.press('Escape')
    const band=page.getByTestId('opportunities-band')
    await expect(band.locator('[data-opportunity-id]')).toHaveCount(items.length)
    const firstOpportunity=[...items].sort((a:any,b:any)=>new Date(a.deadline).valueOf()-new Date(b.deadline).valueOf()).find((item:any)=>item.photo)
    await expect(band.locator('img').first()).toHaveAttribute('src',firstOpportunity.photo)
    await expect(band.locator('[role="timer"]').first()).toBeAttached()
    await expect(band).toContainText('Для кого:')
    const colors=await band.evaluate(element=>({section:getComputedStyle(element.querySelector('section')!).backgroundColor,page:getComputedStyle(document.body).backgroundColor}))
    expect(colors.section).toBe(colors.page)
    const foreground=await band.locator('[data-opportunity-id] article').first().evaluate(element=>({
      card:getComputedStyle(element).color,
      heading:getComputedStyle(element.querySelector('h3')!).color,
      timer:getComputedStyle(element.querySelector('[role="timer"]>span')!).color,
      page:getComputedStyle(document.body).color,
    }))
    expect(foreground.card).toBe(foreground.page)
    expect(foreground.heading).toBe(foreground.page)
    expect(foreground.timer).toBe(foreground.page)
    for(const width of [360,768,1440]){
      await page.setViewportSize({width,height:950});await band.scrollIntoViewIfNeeded()
      const viewport=await band.locator('[data-carousel-viewport]').boundingBox(),slide=await band.locator('.opportunity-carousel-slide').first().boundingBox()
      const columns=Math.round((viewport!.width+20)/(slide!.width+20))
      expect(columns).toBe(width<640?1:width<1024?2:4)
      expect(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)).toBeFalsy()
    }
  }
  expect(errors).toEqual([])
})
test('prototype opportunity save persists and application link records a real click',async({page,request})=>{
  const auth=await(await request.get('/api/creata/v1/auth/me')).json();test.skip(!auth.devAuth,'Requires explicit local auth')
  await page.request.post('/api/creata/v1/auth/dev-login',{data:{role:'reader'}})
  const {items}=await(await request.get('/api/creata/v1/public/opportunities?locale=en')).json();test.skip(!items.length,'Requires development opportunities')
  const item=items[0];await page.goto(`/en/opportunities/${item.id}`)
  const card=page.locator(`[data-opportunity-id="${item.id}"]`),save=card.getByRole('button',{name:/^(Save|Remove from saved)$/})
  await expect(save).toBeEnabled();if(await save.getAttribute('aria-pressed')==='true')await save.click()
  await expect(save).toHaveAttribute('aria-pressed','false');await save.click();await expect(save).toHaveAttribute('aria-pressed','true')
  const saved=await(await page.request.get('/api/creata/v1/account/saved')).json();expect(saved.opportunities.some((opportunity:any)=>opportunity.id===item.id)).toBeTruthy()
  const link=card.getByRole('link',{name:'Apply',exact:true});await expect(link).toHaveAttribute('href',new URL(item.url).href)
  await link.evaluate(element=>element.addEventListener('click',event=>event.preventDefault(),{once:true}))
  const recorded=page.waitForRequest(req=>req.url().endsWith('/public/events')&&req.method()==='POST'&&req.postDataJSON().type==='opportunity_click')
  await link.click();expect((await recorded).postDataJSON().targetId).toBe(item.id)
  await save.click();await expect(save).toHaveAttribute('aria-pressed','false')
})
