import {test,expect} from '@playwright/test'

test.use({baseURL:process.env.CREATA_HOME_TEST_URL,reducedMotion:'reduce'})
test.skip(!process.env.CREATA_HOME_TEST_URL,'Requires an explicit local homepage preview')

test('approved homepage keeps the branded editorial layout and working filters',async({page})=>{
 const errors:string[]=[]
 page.on('pageerror',error=>errors.push(error.message))
 page.on('console',message=>{if(message.type()==='error')errors.push(message.text())})
 page.on('requestfailed',request=>{if(request.failure()?.errorText!=='net::ERR_ABORTED')errors.push(request.url())})
 await page.setViewportSize({width:1440,height:1000})
 await page.goto('/ru/v2')
 await page.evaluate(()=>document.fonts.ready)
 await expect(page.locator('html')).toHaveAttribute('data-theme','light')
 await expect(page.getByRole('heading',{level:1})).toHaveCount(1)
 await expect(page.locator('.home-header-nav')).toBeVisible()
 await expect(page.locator('.site-header .creata-wordmark')).toHaveAccessibleName('Creata News')
 const grid=page.getByTestId('home-story-rail')
 await expect(grid.locator('article')).toHaveCount(6)
 await expect.poll(async()=>Number(await grid.locator('..').getAttribute('data-snap-count'))).toBeGreaterThan(0)
 await expect.poll(()=>grid.locator('article').evaluateAll(nodes=>{const positions=nodes.slice(0,3).map(node=>node.getBoundingClientRect().y);return Math.max(...positions)-Math.min(...positions)})).toBeLessThan(2)
 const cards=await grid.locator('article').evaluateAll(nodes=>nodes.slice(0,4).map(node=>{const r=node.getBoundingClientRect();return{x:r.x,y:r.y,width:r.width}}))
 expect(Math.abs(cards[0].y-cards[2].y)).toBeLessThan(2)
 expect(cards[2].x).toBeGreaterThan(cards[1].x)
 expect(cards[3].y).toBeGreaterThan(cards[0].y+200)
 await page.getByRole('button',{name:'Технологии',exact:true}).click()
 await expect(page.getByRole('button',{name:'Технологии',exact:true})).toHaveAttribute('aria-pressed','true')
 await expect(page.getByRole('button',{name:'Все материалы',exact:true})).toHaveAttribute('aria-pressed','false')
 await page.getByRole('button',{name:'Все материалы',exact:true}).click()
 await expect(grid.locator('article')).toHaveCount(6)
 await expect(page.locator('#home-newspaper-title')).toHaveText('Меньше шума. Больше смысла.')
 const promo=page.getByTestId('home-newspaper-promo')
 await expect(promo.getByRole('link',{name:'Читать выпуск',exact:true})).toHaveAttribute('href',/\/ru\/gazeta\/.+/)
 const footerSize=await page.locator('.home-footer .creata-logo-full').boundingBox()
 expect(footerSize!.width).toBeGreaterThan(1200)
 expect(footerSize!.height).toBeGreaterThan(100)
 await expect(page.locator('.home-footer-subscribe a')).toHaveAttribute('href','/ru/profile#digest')
 const images=page.locator('#main-content img:visible')
 for(const image of await images.all()){
  await image.scrollIntoViewIfNeeded()
  await expect.poll(()=>image.evaluate(node=>(node as HTMLImageElement).complete&&(node as HTMLImageElement).naturalWidth>0)).toBe(true)
 }
 await page.evaluate(()=>scrollTo(0,0))
 await page.screenshot({path:test.info().outputPath('desktop.png'),fullPage:true})
 expect(errors).toEqual([])
})

test('homepage retains discovery, locale switching and real destinations',async({page})=>{
 await page.setViewportSize({width:390,height:844})
 await page.goto('/ru/v2')
 await page.locator('.site-header .original-menu-trigger').click()
 const menu=page.locator('#creata-menu')
 const popular=menu.locator('.home-menu-popular')
 await popular.locator('summary').focus()
 await page.keyboard.press('Enter')
 await expect(popular).toHaveAttribute('open','')
 const carousel=popular.locator('[aria-roledescription="carousel"]')
 await expect.poll(async()=>Number(await carousel.getAttribute('data-snap-count'))).toBeGreaterThan(1)
 await carousel.focus();await carousel.press('ArrowRight')
 await expect(carousel).toHaveAttribute('data-current-index','1')
 await menu.getByRole('link',{name:'Возможности',exact:true}).click()
 await expect(page).toHaveURL(/\/ru\/opportunities$/)
 await expect(page.getByRole('heading',{level:1})).toBeVisible()
 await page.goto('/ru/v2')
 await page.locator('.site-header .original-menu-trigger').click()
 await page.locator('#creata-menu').getByRole('button',{name:'EN',exact:true}).click()
 await expect(page).toHaveURL(/\/en\/v2$/)
 await expect(page.getByRole('heading',{level:1})).toHaveText('The future starts right where you are')
 await page.locator('.home-search-link').click()
 await expect(page).toHaveURL(/\/en\/search$/)
 await expect(page.getByRole('heading',{level:1})).toBeVisible()
 await page.goto('/ru/v2')
 await page.locator('.home-paper-link').click()
 await expect(page).toHaveURL(/\/ru\/gazeta$/)
 await expect(page.getByRole('heading',{level:1})).toBeVisible()
 await page.goto('/ru/v2')
 await page.locator('.home-footer-subscribe a').click()
 await expect(page).toHaveURL(/\/ru\/profile#digest$/)
 await expect(page.getByRole('heading',{level:1})).toBeVisible()
})

test('approved homepage fits every locale and preserves mobile navigation',async({page})=>{
 test.setTimeout(120000)
 for(const locale of ['ru','kk','en']){
  await page.goto('/'+locale+'/v2')
  await expect(page.locator('html')).toHaveAttribute('lang',locale)
  for(const width of [360,768,1000,1440]){
   await page.setViewportSize({width,height:1000})
   await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth-innerWidth)).toBeLessThanOrEqual(1)
   await expect.poll(()=>page.locator('.home-footer-brand').evaluate(node=>node.scrollWidth-node.clientWidth)).toBeLessThanOrEqual(1)
   await expect(page.locator('.site-header .brand-link')).toBeVisible()
  }
 }
 await page.setViewportSize({width:390,height:844})
 await page.goto('/ru/v2')
 const viewport=page.getByTestId('home-story-rail').locator('..')
 await viewport.scrollIntoViewIfNeeded()
 await expect.poll(async()=>Number(await viewport.getAttribute('data-snap-count'))).toBeGreaterThan(1)
 await viewport.focus()
 await viewport.press('ArrowRight')
 await expect(viewport).toHaveAttribute('data-current-index','1')
 const theme=await page.locator('html').getAttribute('data-theme')
 await page.locator('.site-header .original-menu-trigger').click()
 await page.locator('#creata-menu .theme-toggle').click()
 await expect(page.locator('html')).toHaveAttribute('data-theme',theme==='dark'?'light':'dark')
 await page.reload()
 await expect(page.locator('html')).toHaveAttribute('data-theme',theme==='dark'?'light':'dark')
 await page.locator('.site-header .original-menu-trigger').click()
 await page.locator('#creata-menu .theme-toggle').click()
 await expect(page.locator('#creata-menu')).toBeVisible()
 await page.keyboard.press('Escape')
 await expect(page.locator('#creata-menu')).not.toBeVisible()
 await expect(page.locator('.site-header .original-menu-trigger')).toBeFocused()
 for(const image of await page.locator('#main-content img:visible').all()){
  await image.scrollIntoViewIfNeeded()
  await expect.poll(()=>image.evaluate(node=>(node as HTMLImageElement).complete&&(node as HTMLImageElement).naturalWidth>0)).toBe(true)
 }
 await page.locator('.site-header .brand-link').click()
 await page.evaluate(()=>scrollTo(0,0))
 await page.screenshot({path:test.info().outputPath('mobile.png'),fullPage:true})
})
