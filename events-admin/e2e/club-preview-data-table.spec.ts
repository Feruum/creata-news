import { expect, test } from '@playwright/test'

test('column resizing supports keyboard, pointer and reset without sorting the table', async ({ page }) => {
  await page.goto('/admin?closed&resizeColumns')
  const handle = page.getByRole('separator', { name: 'Resize title column', exact: true })
  const header = page.getByRole('columnheader').filter({ has: handle })
  await expect(handle).toHaveAttribute('aria-valuenow', '200')
  await handle.focus()
  await page.keyboard.press('ArrowRight')
  await expect(handle).toHaveAttribute('aria-valuenow', '210')
  await page.keyboard.press('ArrowLeft')
  await expect(handle).toHaveAttribute('aria-valuenow', '200')
  for (let step = 0; step < 10; step++) await page.keyboard.press('ArrowLeft')
  await expect(handle).toHaveAttribute('aria-valuenow', '150')
  await page.keyboard.press('Enter')
  await page.keyboard.press('Space')
  await expect(header).toHaveAttribute('aria-sort', 'none')
  await expect(page.getByTestId('club-preview')).toHaveCount(0)

  const bounds = await handle.boundingBox()
  if (!bounds) throw new Error('Column resize handle is missing')
  await page.mouse.move(bounds.x + bounds.width / 2, bounds.y + bounds.height / 2)
  await page.mouse.down()
  await page.mouse.move(bounds.x + 80, bounds.y + bounds.height / 2, { steps: 5 })
  await page.mouse.up()
  await expect.poll(async () => Number(await handle.getAttribute('aria-valuenow'))).toBeGreaterThan(200)
  await handle.dblclick()
  await expect(handle).toHaveAttribute('aria-valuenow', '200')
  await expect(header).toHaveAttribute('aria-sort', 'none')

  await page.goto('/admin?closed&loadingTable')
  const table = page.getByRole('table', { name: 'clubs data table', exact: true })
  await expect(table).toHaveAttribute('aria-busy', 'true')
  await expect(table.locator('tbody tr')).toHaveCount(10)
  const columnCount = await table.getByRole('columnheader').count()
  await expect(table.locator('tbody tr').first().getByRole('cell')).toHaveCount(columnCount)
})
