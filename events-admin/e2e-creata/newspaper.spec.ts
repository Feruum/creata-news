import { expect, test } from '@playwright/test'
import { readFileSync } from 'node:fs'
import { resolve } from 'node:path'

test('newsroom creates a photographed issue, previews, publishes a snapshot and removes it from the archive', async ({ page, context }) => {
  test.setTimeout(120_000)
  const web = process.env.CREATA_NEWSPAPER_WEB_URL || 'http://localhost:3002'
  const slug = `browser-${Date.now()}`, title = `Газета · проверка ${slug}`
  const login = await page.request.post('/api/creata/v1/auth/dev-login', { data: { role: 'chief_editor' } })
  expect(login.ok()).toBeTruthy()
  await page.goto('/newspapers')
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Газета')
  await page.getByRole('button', { name: 'Создать выпуск', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Номер выпуска').fill('02')
  await dialog.getByLabel('Адрес выпуска').fill(slug)
  await dialog.getByLabel('Название выпуска').fill(title)
  await dialog.getByLabel('Месяц выпуска').fill('2026-11')
  await dialog.getByRole('button', { name: 'Создать выпуск', exact: true }).click()
  await expect(page).toHaveURL(/\/newspapers\/[a-z0-9]+$/)
  const issueId = page.url().split('/').pop()!
  test.info().annotations.push({ type: 'newspaperId', description: issueId })
  const rows = page.locator('.newspaper-picker-item')
  await expect(rows.first()).toBeVisible()
  const secondTitle = await rows.nth(1).locator('span').first().innerText()
  await rows.nth(0).getByRole('button', { name: 'Добавить в выпуск', exact: true }).click()
  await rows.nth(1).getByRole('button', { name: 'Добавить в выпуск', exact: true }).click()
  await page.getByRole('button', { name: 'Опустить статью 1', exact: true }).click()
  await expect(page.locator('.newspaper-selected>li').first()).toContainText(secondTitle)
  await page.getByLabel('Вступление').fill('Сохранённое вступление выпуска')
  await page.getByLabel('Автор изображения').fill('Creata News')
  await page.getByLabel('Права на использование').fill('Собственная съёмка')
  await page.getByLabel('Подпись', { exact: true }).fill('Обложка нового выпуска')
  await page.getByLabel('Загрузить изображение', { exact: true }).setInputFiles({ name: 'cover.webp', mimeType: 'image/webp', buffer: readFileSync(resolve(import.meta.dirname, '../../creatanews/public/newspaper/issues/01/media/hero.webp')) })
  await expect(page.locator('.newspaper-photo-preview')).toBeVisible()
  await page.getByRole('button', { name: 'Фото статьи 2', exact: true }).click()
  const photoDialog = page.getByRole('dialog')
  await photoDialog.getByLabel('Автор изображения').fill('Creata photo team')
  await photoDialog.getByLabel('Права на использование').fill('Собственная съёмка')
  await photoDialog.getByLabel('Подпись', { exact: true }).fill('Отдельное фото статьи')
  await photoDialog.getByLabel('Загрузить изображение', { exact: true }).setInputFiles({ name: 'article.webp', mimeType: 'image/webp', buffer: readFileSync(resolve(import.meta.dirname, '../../creatanews/public/newspaper/issues/01/media/hero.webp')) })
  await expect(photoDialog.locator('.newspaper-photo-preview')).toHaveAttribute('src', /\/media\/images\//)
  await photoDialog.getByRole('button', { name: 'Закрыть', exact: true }).click()
  await page.getByRole('button', { name: 'Сохранить', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Сохранить', exact: true })).toBeDisabled()
  await page.reload()
  await expect(page.locator('.newspaper-selected>li')).toHaveCount(2)
  await expect(page.locator('.newspaper-photo-preview')).toBeVisible()
  expect((await page.request.get(`/api/creata/v1/public/newspapers/${slug}`)).status()).toBe(404)
  const [preview] = await Promise.all([context.waitForEvent('page'), page.getByRole('link', { name: 'Предпросмотр', exact: true }).click()])
  await expect(preview.locator('.preview-banner')).toBeVisible()
  await expect(preview.locator('.managed-newspaper-sheet')).toHaveCount(2)
  await expect(preview.getByRole('heading', { level: 1 })).toHaveText(secondTitle)
  await preview.close()
  await page.screenshot({ path: resolve(import.meta.dirname, '../../.frontend-workbench/gazeta/admin-issue.png'), fullPage: true })
  await page.getByRole('button', { name: 'Опубликовать', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Опубликовать', exact: true }).click()
  await expect(page.locator('.page-head .badge')).toHaveText('Опубликовано')
  const publicPage = await context.newPage()
  await publicPage.goto(`${web}/ru/gazeta`)
  const edition = publicPage.locator('.gazeta-edition').filter({ hasText: title })
  await expect(edition).toBeVisible()
  await edition.getByRole('link', { name: 'Читать выпуск', exact: true }).click()
  await expect(publicPage).toHaveURL(new RegExp(`/ru/gazeta/${slug}$`))
  await expect(publicPage.getByRole('heading', { level: 1 })).toHaveText(secondTitle)
  await expect(publicPage.getByText('Обложка нового выпуска · Creata News')).toBeVisible()
  await expect(publicPage.getByText('Отдельное фото статьи · Creata photo team')).toBeVisible()
  const sheet = await publicPage.locator('.managed-newspaper-sheet').first().boundingBox()
  const headline = await publicPage.getByRole('heading', { level: 1 }).boundingBox()
  expect(headline!.width).toBeGreaterThan(sheet!.width * .75)
  await publicPage.screenshot({ path: resolve(import.meta.dirname, '../../.frontend-workbench/gazeta/published-managed-issue.png') })
  for (const width of [360, 768]) {
    await publicPage.setViewportSize({ width, height: 900 })
    expect(await publicPage.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false)
  }
  await page.getByLabel('Вступление').fill('Изменения ещё не опубликованы')
  await page.getByRole('button', { name: 'Сохранить', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Сохранить', exact: true })).toBeDisabled()
  const stillPublished = await (await page.request.get(`/api/creata/v1/public/newspapers/${slug}`)).json()
  expect(stillPublished.description).toBe('Сохранённое вступление выпуска')
  await page.getByRole('button', { name: 'Снять с публикации', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Снять с публикации', exact: true }).click()
  await expect(page.locator('.page-head .badge')).toHaveText('Черновик')
  expect((await page.request.get(`/api/creata/v1/public/newspapers/${slug}`)).status()).toBe(404)
  await publicPage.goto(`${web}/ru/gazeta`)
  await expect(publicPage.locator('.gazeta-edition').filter({ hasText: title })).toHaveCount(0)
  await expect(publicPage.locator('.gazeta-edition').filter({ hasText: '№01' })).toBeVisible()
  await page.setViewportSize({ width: 360, height: 900 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false)
  console.log(`Verified newspaper issue ${issueId}`)
})

test.afterEach(async ({ page }) => {
  const id = test.info().annotations.find(annotation => annotation.type === 'newspaperId')?.description
  if (!id) return
  const session = await (await page.request.get('/api/creata/v1/auth/me')).json()
  const response = await page.request.get(`/api/creata/v1/admin/newspapers/${id}`)
  if (!response.ok()) return
  const issue = await response.json()
  if (issue.publishedRevision) await page.request.post(`/api/creata/v1/admin/newspapers/${id}/unpublish`, { headers: { 'X-CSRF-Token': session.csrfToken }, data: { expectedRevision: issue.revision } })
})
